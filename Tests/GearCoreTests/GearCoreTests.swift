final class FakeIO: TerminalIO {
    var sent: [String] = []
    /// nil 이면 화면을 못 읽는 터미널.
    var screens: [[String]]?
    private var reads = 0

    var onEnter: (() -> Void)?

    func type(_ text: String) throws { sent.append(text) }
    func press(_ key: Key) throws {
        sent.append(key.bytes)
        if key == .enter { onEnter?() }
    }
    func screen() -> [String]? {
        guard let screens else { return nil }
        defer { reads += 1 }
        return screens[min(reads, screens.count - 1)]
    }
}

final class PlanTests: XCTestCase {
    func testKeyBytes() {
        XCTAssertEqual(Key.ctrl("s").bytes, "\u{13}")
        XCTAssertEqual(Key.ctrl("a").bytes, "\u{01}")
        XCTAssertEqual(Key.up.bytes, "\u{1B}[A")
        XCTAssertEqual(Key.enter.bytes, "\r")
    }

    func testClaudePlanStashesBeforeEachCommand() {
        let steps = Plans.claude(AgentPreset(model: "opus", effort: "xhigh"))
        let inputs = steps.compactMap { step -> String? in
            switch step {
            case .text(let text): return text
            case .key(let key): return key.bytes
            default: return nil
            }
        }
        XCTAssertEqual(inputs, ["\u{13}", "/model opus", "\r", "\u{13}", "/effort xhigh", "\r"])
    }

    func testCodexPlanMovesUpFromAnchorRow() {
        for row in 1...4 {
            let steps = Plans.codex(modelIndex: 2, effortRow: row)
            XCTAssertEqual(steps.filter { $0 == .key(.up) }.count, 5 - row, "row \(row)")
            XCTAssertTrue(steps.contains(.text("2")))
            XCTAssertTrue(steps.contains(.text("s")), "세션 한정(s)으로 확정해야 기본값을 안 건드린다")
            XCTAssertFalse(steps.contains(.text(String(row))) && row != 2, "effort 는 숫자 키로 고르지 않는다(기본값까지 저장된다)")
        }
    }
}

